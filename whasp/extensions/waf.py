"""Web application firewall: block hostile requests in nginx before they reach your sites.

Whasp writes two files into the nginx folder from the rules below and the lists you manage here:
  * conf.d/whasp-waf.conf       http-level `map`/`geo` blocks that set $whasp_block to 1 for a bad request
  * snippets/whasp-waf.inc      `if ($whasp_block) { return 403; }`, included by each protected site
`Protect sites` adds that include to every site in sites-available (and `Unprotect` removes it). The same rules
are evaluated in Python by `Test a request`, so you can check a URL or agent without sending real traffic.
"""

