import ipaddress
import os
import re
from pathlib import Path

from ..core import audit, config, plat
from ..core.errors import PanelError
from ..core.shell import run
from . import Extension

__all__ = ["BUILTIN_AGENTS", "BUILTIN_PATHS", "EXT", "check_request", "render_conf"]

WIN = plat.IS_WIN
EXT = Extension(
    "waf",
    "Firewall (WAF)",
    "🛡",
    order=52,
    group="Security",
    description="Web application firewall for nginx: blocks injection, traversal, scanners and listed addresses",
)
INCLUDE = "include snippets/whasp-waf.inc;"
MARK = "# whasp-waf"

# Regexes (PCRE, case-insensitive) matched against the request URI (path and query string).
BUILTIN_PATHS = {
    "SQL injection": r"(union(\s|%20|\+)+(all(\s|%20|\+)+)?select|select.+from|insert(\s|%20|\+)+into|drop(\s|%20|\+)+table|or(\s|%20|\+)+1=1|sleep\(\d)",
    "Cross-site scripting": r"(<script|%3cscript|javascript:|onerror=|onload=|document\.cookie)",
    "Path traversal": r"(\.\./|\.\.%2f|%2e%2e/|%252e%252e|/etc/passwd|boot\.ini)",
    "Code injection": r"(base64_decode\(|eval\(|php://input|data://|expect://|/bin/(ba)?sh)",
    "Sensitive files": r"(/\.(git|svn|hg|env|aws|ssh)(/|$|\?)|wp-config\.php\.|\.(sql|bak|old|swp)(\?|$))",
}
BUILTIN_AGENTS = (
    "sqlmap",
    "nikto",
    "nmap",
    "masscan",
    "acunetix",
    "nessus",
    "wpscan",
    "dirbuster",
    "havij",
    "zgrab",
    "python-requests/0",
)
_BAD = re.compile(r'["\n\r;{}]|\$\w')  # characters that could break out of an nginx string


def _cfg():
    w = config.cfg.setdefault("waf", {})
    for k, v in (("enabled", False), ("ips_deny", []), ("ips_allow", []), ("agents", []), ("paths", []), ("builtin", True)):
        w.setdefault(k, v)
    return w


def _regex(value, what):
    v = str(value or "").strip()
    if not v or len(v) > 200 or _BAD.search(v):
        raise PanelError(f"invalid {what}: up to 200 characters, none of  \" ; {{ }} or $name")
    try:
        re.compile(v)
    except re.error as e:
        raise PanelError(f"invalid {what}: {e}")
    return v


def _net(value):
    try:
        return str(ipaddress.ip_network(str(value or "").strip(), strict=False))
    except ValueError:
        raise PanelError("enter an IPv4/IPv6 address or a network such as 203.0.113.0/24")


def _nginx_dir():
    env = os.environ.get("WHASP_NGINX_DIR") or config.cfg.get("nginx_dir")
    if env:
        return Path(env)
    if WIN:
        exe = plat.which("nginx")
        return Path(exe).parent / "conf" if exe else Path(os.environ.get("SystemDrive", "C:") + "\\nginx\\conf")
    return Path("/etc/nginx")


def _paths():
    w = _cfg()
    out = list(BUILTIN_PATHS.values()) if w["builtin"] else []
    return out + w["paths"]


def _agents():
    w = _cfg()
    return (list(BUILTIN_AGENTS) if w["builtin"] else []) + w["agents"]


def check_request(uri="", agent="", ip=""):
    """Return (blocked, reason) using the same rules that are written to nginx."""
    w = _cfg()
    if ip:
        try:
            addr = ipaddress.ip_address(ip)
        except ValueError:
            raise PanelError("invalid IP address")
        if any(addr in ipaddress.ip_network(n, strict=False) for n in w["ips_allow"]):
            return False, "address is on the allow list"
        if any(addr in ipaddress.ip_network(n, strict=False) for n in w["ips_deny"]):
            return True, "address is on the deny list"
    for name, rx in ([(n, r) for n, r in BUILTIN_PATHS.items()] if w["builtin"] else []) + [
        ("custom path rule " + r, r) for r in w["paths"]
    ]:
        if uri and re.search(rx, uri, re.I):
            return True, name
    for a in _agents():
        if agent and a.lower() in agent.lower():
            return True, "blocked agent: " + a
    return False, "allowed"


def render_conf(w=None):
    """nginx http-level configuration for the current rules (pure function, easy to test)."""
    w = w or _cfg()
    lines = ["# Generated by Whasp (Security > Firewall). Edit the rules in the panel, not this file.", ""]
    lines += ["map $request_uri $whasp_bad_uri {", "    default 0;"]
    lines += [f'    "~*{r}" 1;' for r in _paths()]
    lines += ["}", "", "map $http_user_agent $whasp_bad_agent {", "    default 0;"]
    lines += [f'    "~*{re.escape(a)}" 1;' for a in _agents()]
    lines += ["}", "", "geo $remote_addr $whasp_ip {", "    default 0;"]
    lines += [f"    {n} 1;" for n in w["ips_deny"]]
    lines += [f"    {n} 2;" for n in w["ips_allow"]]  # a later (more specific) allow entry wins by nginx geo rules
    lines += ["}", "", "map $whasp_ip$whasp_bad_uri$whasp_bad_agent $whasp_block {", "    default 0;"]
    lines += ["    ~^2 0;", "    ~^1 1;", "    ~^.[1]. 1;", "    ~^..1$ 1;", "}", ""]
    return "\n".join(lines)


INC = "if ($whasp_block) {\n    return 403;\n}\n"


def _write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def _apply():
    d = _nginx_dir()
    if not d.is_dir():
        raise PanelError("nginx is not installed yet (no config folder). Install it from Services > Software library.", 404)
    w = _cfg()
    conf, inc = d / "conf.d" / "whasp-waf.conf", d / "snippets" / "whasp-waf.inc"
    old = conf.read_text(encoding="utf-8") if conf.exists() else None
    _write(conf, render_conf(w))
    _write(inc, INC if w["enabled"] else "# WAF switched off in Whasp\n")
    if plat.which("nginx"):
        rc, out = run(["nginx", "-t"], cwd=str(d.parent) if WIN else None)
        if rc:  # never leave nginx with a configuration that does not load
            if old is None:
                conf.unlink(missing_ok=True)
            else:
                _write(conf, old)
            raise PanelError("nginx rejected the rules, nothing was changed: " + out[-400:])
        run(["nginx", "-s", "reload"], cwd=str(d.parent) if WIN else None)
    return conf


def _sites():
    d = _nginx_dir() / "sites-available"
    return sorted(f for f in d.glob("*") if f.is_file()) if d.is_dir() else []


def _protected(f):
    try:
        return INCLUDE in f.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return False


@EXT.route("status")
def status(p):
    w = _cfg()
    sites = _sites()
    return {
        "enabled": w["enabled"],
        "rules": len(_paths()) + len(_agents()) + len(w["ips_deny"]),
        "sites": len(sites),
        "protected": sum(_protected(f) for f in sites),
        "nginx": bool(plat.which("nginx")),
    }


@EXT.route("stats")
def stats(p):
    s = status(p)
    return [
        {"label": "WAF", "value": "on" if s["enabled"] else "off", "state": "ok" if s["enabled"] else "warn"},
        {"label": "Rules", "value": s["rules"]},
        {"label": "Protected sites", "value": f"{s['protected']}/{s['sites']}"},
    ]


@EXT.route("rules")
def rules(p):
    w = _cfg()
    rows = []
    if w["builtin"]:
        rows += [{"id": "b:" + n, "kind": "built-in path", "value": n, "builtin": True} for n in BUILTIN_PATHS]
        rows += [{"id": "b:a:" + a, "kind": "built-in agent", "value": a, "builtin": True} for a in BUILTIN_AGENTS]
    for kind, key in (("deny IP", "ips_deny"), ("allow IP", "ips_allow"), ("agent", "agents"), ("path regex", "paths")):
        rows += [{"id": f"{key}:{v}", "kind": kind, "value": v, "builtin": False} for v in w[key]]
    return rows


@EXT.route("add", write=True)
def add(p):
    kind, value = str(p.get("kind", "")), p.get("value", "")
    w = _cfg()
    if kind in ("ips_deny", "ips_allow"):
        value = _net(value)
    elif kind == "agents":
        value = str(value).strip()
        if not value or len(value) > 100 or _BAD.search(value):
            raise PanelError("invalid agent text")
    elif kind == "paths":
        value = _regex(value, "path regex")
    else:
        raise PanelError("kind must be ips_deny, ips_allow, agents or paths")
    if value in w[kind]:
        raise PanelError("already in the list")
    w[kind].append(value)
    config.save()
    return {"text": f"added {value}; press Apply to write it to nginx"}


@EXT.route("delete", write=True)
def delete(p):
    rid = str(p.get("id", ""))
    key, _, value = rid.partition(":")
    w = _cfg()
    if key not in ("ips_deny", "ips_allow", "agents", "paths") or value not in w[key]:
        raise PanelError("unknown rule (built-in rules are switched off with the Built-in rules toggle)", 404)
    w[key].remove(value)
    config.save()
    return {"ok": True}


@EXT.route("toggle", write=True)
def toggle(p):
    w = _cfg()
    what = str(p.get("what", "enabled"))
    if what not in ("enabled", "builtin"):
        raise PanelError("what must be enabled or builtin")
    w[what] = bool(p.get("on", not w[what])) if not isinstance(p.get("on"), str) else p["on"] in ("1", "true", "on")
    config.save()
    return {"text": f"{what} is now {'on' if w[what] else 'off'}; press Apply to write it to nginx"}


@EXT.route("apply", write=True)
def apply_(p):
    conf = _apply()
    audit.log("waf_apply", path=str(conf))
    return {"text": f"wrote {conf} and reloaded nginx"}


@EXT.route("sites")
def sites(p):
    return [{"name": f.name, "protected": _protected(f)} for f in _sites()]


@EXT.route("protect", write=True)
def protect(p):
    name, off = str(p.get("name", "")), str(p.get("off", "")) in ("1", "true", "True")
    targets = [f for f in _sites() if name in ("", "*", f.name)]
    if not targets:
        raise PanelError("unknown site", 404)
    _apply()
    changed = 0
    for f in targets:
        text = f.read_text(encoding="utf-8", errors="replace")
        if off:
            new = re.sub(r"\n[ \t]*" + re.escape(INCLUDE) + r"[ \t]*" + re.escape(MARK) + r"[ \t]*", "", text)
        elif INCLUDE in text:
            continue
        else:
            new, n = re.subn(r"(\bserver\s*\{)", lambda m: f"{m.group(1)}\n    {INCLUDE} {MARK}", text, count=1)
            if not n:
                continue
        if new != text:
            _write(f, new)
            changed += 1
    if plat.which("nginx"):
        rc, out = run(["nginx", "-t"], cwd=str(_nginx_dir().parent) if WIN else None)
        if rc:
            raise PanelError("nginx -t failed after the change: " + out[-400:])
        run(["nginx", "-s", "reload"], cwd=str(_nginx_dir().parent) if WIN else None)
    return {"text": f"{'removed protection from' if off else 'protected'} {changed} site(s)"}


@EXT.route("test", write=False)
def test(p):
    blocked, why = check_request(str(p.get("uri", "")), str(p.get("agent", "")), str(p.get("ip", "")).strip())
    return {"text": ("BLOCKED (403): " if blocked else "ALLOWED: ") + why}


@EXT.route("recent")
def recent(p):
    """Count 403 responses per client address in the newest nginx access log lines (what the WAF has stopped)."""
    log = Path("/var/log/nginx/access.log") if not WIN else _nginx_dir().parent / "logs" / "access.log"
    counts = {}
    try:
        with open(log, "rb") as f:
            f.seek(0, 2)
            f.seek(max(0, f.tell() - 1_000_000))
            for line in f.read().decode("utf-8", "replace").splitlines():
                m = re.match(r'(\S+) .*?" 403 ', line)
                if m:
                    counts[m.group(1)] = counts.get(m.group(1), 0) + 1
    except OSError:
        return []
    return [{"ip": k, "blocked": v} for k, v in sorted(counts.items(), key=lambda kv: -kv[1])[:50]]


